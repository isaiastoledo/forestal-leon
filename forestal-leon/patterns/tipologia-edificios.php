<div class="wp-block-group"><!-- wp:paragraph -->
<p>La madera laminada estructural y el sistema Timber Frame permiten hoy construir edificios de madera de varios pisos con estándares técnicos equivalentes o superiores a los del hormigón y el acero. Su bajo peso estructural es una ventaja que se traduce en múltiples beneficios concretos: al reducir la masa de la estructura, se disminuyen proporcionalmente las fuerzas sísmicas que actúan sobre el edificio, se simplifican y abaratan las fundaciones y se abre la posibilidad de ampliar edificios existentes con plantas adicionales sin intervenir la estructura original.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Todo esto, sumado a menores tiempos de obra y costos de construcción más competitivos, hace de la madera para construcción de edificios una decisión técnica y económicamente superior en proyectos de cualquier escala.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>En Forestal León fabricamos los componentes estructurales para una amplia gama de tipologías: edificios residenciales en madera, strip centers, edificios comerciales e industriales. Todo a través de un proceso de construcción industrializada en madera, donde el alto grado de prefabricación y el enfoque en construcción modular acortan considerablemente los tiempos de obra sin sacrificar calidad, con cada pieza diseñada y fabricada con tecnología BIM para garantizar precisión en la fabricación y eficiencia en el montaje en obra.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>La combinación de madera estructural con hormigón, acero o vidrio permite además desarrollar soluciones híbridas especialmente rentables, que vinculan las ventajas de la construcción en madera con los requerimientos técnicos y estéticos de cada proyecto.</p>
