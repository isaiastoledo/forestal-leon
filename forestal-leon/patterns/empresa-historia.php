<div class="wp-block-group"><!-- wp:paragraph -->
<p>El origen de Forestal León se remonta a 1957, cuando Celso Viñuela García, proveniente de la provincia de León, España, llegó a Chile con 24 años. Tras sus primeros años como empleado y comerciante, en 1973 adquirió una barraca en San Bernardo, Santiago, fundando Comercial Viñuela S.A. y sentando las bases de lo que sería un proyecto forestal de largo aliento.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>En 1991, don Celso y sus hijos fundaron Forestal León Ltda., con un objetivo concreto: producir madera directamente desde el bosque para abastecer la barraca de Santiago, integrando por primera vez la cadena productiva de origen a destino.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>En 1999, la empresa comenzó a trabajar en la zona de Coelemu, desarrollando gradualmente su presencia en la región hasta consolidar lo que hoy es su planta industrial. Con el tiempo, la gama de productos fue creciendo y diversificándose progresivamente, desde las primeras maderas dimensionadas hasta los tableros, laminados y soluciones estructurales de la actualidad, acompañada de una expansión hacia los mercados más exigentes de Chile y el mundo.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>En 2012 nació Energía León S.A., transformando los residuos del proceso productivo en energía eléctrica y vapor para abastecer las propias instalaciones y las comunidades aledañas, consolidando un modelo productivo de aprovechamiento integral.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>En 2022 se incorporaron dos nuevas áreas estratégicas. Vivero León inició la producción de plantas de alta calidad genética para reforestar los bosques propios de la empresa y vender plantas a otros clientes, mejorando la sanidad y el crecimiento de los pinos. En paralelo, el área de Construcción en Madera amplió el alcance del negocio hacia soluciones constructivas especializadas, integrando madera y acero desde la producción hasta la obra terminada.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Hoy, con más de 50 años de trayectoria, Forestal León proyecta su futuro con un objetivo claro: liderar la construcción en madera en Chile y América.</p>
