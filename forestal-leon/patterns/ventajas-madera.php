<h2 class="wp-block-heading is-style-titulo-seccion">La madera como material de construcción estructural</h2>
<!-- /wp:heading -->

<!-- wp:paragraph {"className":"is-style-subtitulo-seccion"} -->
<p class="is-style-subtitulo-seccion">Construir en madera no es una tendencia. Es una decisión técnica respaldada por la ciencia y las necesidades modernas.</p>
<!-- /wp:paragraph --></div>
<!-- /wp:group -->

<!-- wp:group {"style":{"spacing":{"blockGap":"var:preset|spacing|50"}},"layout":{"type":"constrained"}} -->
<div class="wp-block-group"><!-- wp:paragraph {"className":"is-style-entradilla"} -->
<p class="is-style-entradilla">La madera lleva siglos siendo parte de la construcción. Lo que ha cambiado es la ciencia detrás de ella. Hoy, con tecnología de fabricación de alta precisión y profundo conocimiento de sus propiedades estructurales, la madera de ingeniería es un material que compite de igual a igual con el hormigón y el acero, y los supera en varios aspectos críticos para la construcción en la actualidad.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3,"fontSize":"heading-s"} -->
<h3 class="wp-block-heading has-heading-s-font-size">Ligereza estructural</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>La madera es significativamente más liviana que el hormigón y el acero, reduciendo las cargas sobre las fundaciones y los costos asociados a ellas. Esta característica es especialmente determinante en proyectos de ampliación de edificios existentes, donde agregar plantas adicionales requiere un material que no comprometa la capacidad portante original de la estructura.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3,"fontSize":"heading-s"} -->
<h3 class="wp-block-heading has-heading-s-font-size">Prefabricación y velocidad</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Los componentes estructurales de madera se fabrican en planta con un alto grado de prefabricación y llegan a obra prácticamente terminados. Esto elimina los tiempos de fraguado y curado propios del hormigón, reduce el equipamiento necesario en terreno, estandariza la calidad y acorta considerablemente los plazos de construcción. En proyectos de gran escala, esto puede significar semanas o meses de diferencia en el plazo de entrega, permitiendo una utilización más temprana del edificio y reduciendo los períodos de financiación del proyecto.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3,"fontSize":"heading-s"} -->
<h3 class="wp-block-heading has-heading-s-font-size">Resistencia técnica superior</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>La madera laminada destaca por propiedades estáticas excepcionales. En relación a su peso propio, soporta cargas muy superiores a las del acero, mientras que su resistencia a la compresión es comparable a la del hormigón armado. Puede fabricarse en elementos de grandes dimensiones tanto en largo como en sección, abriendo posibilidades que los materiales convencionales difícilmente pueden igualar al mismo costo.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3,"fontSize":"heading-s"} -->
<h3 class="wp-block-heading has-heading-s-font-size">Resistencia a la torsión</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>La composición de múltiples láminas encoladas con adhesivos industriales resistentes e impermeables otorga a la madera laminada una alta resistencia a la torsión y deformación. A diferencia de la madera maciza convencional, la orientación alternada de las fibras en cada lámina neutraliza las tensiones internas, manteniendo la geometría estructural de cada pieza bajo cargas dinámicas, variables y de largo plazo.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3,"fontSize":"heading-s"} -->
<h3 class="wp-block-heading has-heading-s-font-size">Comportamiento sísmico</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Chile es uno de los países con mayor actividad sísmica del planeta, lo que convierte el comportamiento sísmico en un criterio no negociable en cualquier decisión constructiva. La madera laminada tiene propiedades sísmicas sobresalientes: su flexibilidad estructural, combinada con su bajo peso y alta resistencia, permite absorber y disipar la energía de un sismo de forma eficiente, reduciendo el riesgo de colapso estructural.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3,"fontSize":"heading-s"} -->
<h3 class="wp-block-heading has-heading-s-font-size">Comportamiento ante el fuego</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Contrario a la percepción común, la madera laminada tiene un mejor comportamiento ante el fuego que el acero. Al exponerse al fuego, forma una capa superficial de carbón que actúa como aislante térmico natural, protegiendo el núcleo estructural y manteniendo su capacidad portante por un tiempo considerablemente mayor que una viga de acero, que pierde resistencia rápidamente al alcanzar altas temperaturas. Esto se traduce en estructuras más seguras y con mayor tiempo de evacuación en situaciones de emergencia.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3,"fontSize":"heading-s"} -->
<h3 class="wp-block-heading has-heading-s-font-size">Tratamiento de impregnado</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>En Forestal León abrimos la posibilidad a aplicar tratamientos químicos de impregnado en planta que elevan significativamente la durabilidad estructural de la madera. El resultado es una madera estructural con una vida útil extendida y garantizada, apta para proyectos en zonas de alta humedad, exteriores o ambientes industriales de alta corrosión o propensos al ataque de insectos.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3,"fontSize":"heading-s"} -->
<h3 class="wp-block-heading has-heading-s-font-size">Versatilidad arquitectónica</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>La madera laminada puede fabricarse en una amplia gama de formas, tamaños y configuraciones, permitiendo grandes luces sin apoyos intermedios, estructuras curvas y espacios abiertos de gran altura. Una característica distintiva es que los elementos estructurales funcionan simultáneamente como elementos de terminación y decoración, eliminando revestimientos adicionales y convirtiendo la madera a la vista en un atributo del diseño arquitectónico.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3,"fontSize":"heading-s"} -->
<h3 class="wp-block-heading has-heading-s-font-size">Menor costo total de obra</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>La construcción en madera estructural es más económica que la construcción tradicional cuando se considera el costo total del proyecto. Menores tiempos de obra, menor mano de obra en terreno, fundaciones más simples y reducción del equipamiento logístico se suman para generar un ahorro concreto y medible frente al hormigón y el acero. Para proyectos de uso comercial, turístico o industrial, donde cada día de obra tiene un costo financiero, esta ventaja es especialmente significativa.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3,"fontSize":"heading-s"} -->
<h3 class="wp-block-heading has-heading-s-font-size">Certificación FSC</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>Las vigas laminadas de Forestal León cuentan con certificación FSC (Forest Stewardship Council), el sello internacional que garantiza que la madera utilizada proviene de bosques gestionados de forma responsable.</p>
<!-- /wp:paragraph -->

<!-- wp:heading {"level":3,"fontSize":"heading-s"} -->
<h3 class="wp-block-heading has-heading-s-font-size">Soluciones híbridas</h3>
<!-- /wp:heading -->

<!-- wp:paragraph -->
<p>La madera no solo compite con los materiales convencionales, también puede complementarlos. Las combinaciones de madera estructural con hormigón, acero y vidrio generan soluciones híbridas que aprovechan las ventajas de cada material, reducen costos y responden a las preferencias estéticas y técnicas de cada proyecto. Esta compatibilidad hace de la madera laminada un material integrable en prácticamente cualquier concepto arquitectónico, desde proyectos de nueva construcción hasta ampliaciones y renovaciones de edificios existentes.</p>
