<div class="wp-block-group"><!-- wp:paragraph -->
<p>Cada proyecto de construcción en madera es un desafío único. Detrás de cada obra, ya sea una vivienda unifamiliar, un edificio de varios pisos, un lodge turístico, un galpón industrial o una ampliación, hay decisiones técnicas que determinan su éxito. En Forestal León fabricamos los componentes estructurales que hacen posible construir en madera con la precisión, velocidad y seguridad que cada proyecto exige.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Nuestra especialidad es el <strong>Glulam</strong>, madera laminada encolada que se puede fabricar en una amplia gama de formas, tamaños y configuraciones. Con vigas y pilares laminados desarrollamos estructuras con grandes espacios abiertos, cerchas de madera, cubiertas y proyectos de alta complejidad arquitectónica, con un acabado superficial que convierte la madera a la vista en un atributo del diseño.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Trabajamos con sistemas <strong>Timber Frame</strong>: vigas laminadas estructurales, pilares de madera laminada, conectores metálicos y procesos industrializados para edificios eficientes y de montaje acelerado. Cada componente sale de nuestra planta en Coelemu modelado con tecnología BIM y mecanizado con robótica de 5 ejes. Las uniones y conexiones vienen incluidas, listas para montar en obra.</p>
<!-- /wp:paragraph -->

<!-- wp:paragraph -->
<p>Como productores de madera controlamos toda la cadena, desde el bosque hasta la obra terminada. Eso nos permite gestionar cada proyecto sin depender de terceros para el abastecimiento, con control total sobre plazos, calidad y costos. Las posibilidades abarcan desde edificios, lodges, gimnasios y galpones hasta pérgolas, cobertizos y cerchas.</p>
